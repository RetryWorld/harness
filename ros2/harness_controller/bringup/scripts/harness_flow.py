RULE = "=" * 78


def summarise(obs: Observation, limit: int = 6):
    if obs.decode_errors:
        print("  !! event decode errors (the ring framing and this decoder disagree):")
        for err in obs.decode_errors[:3]:
            print(f"     {err}")

    if not obs.decisions:
        print("  (no decision messages — is the controller active? check the launch terminal)")
    else:
        tally: dict[tuple[str, str], int] = {}
        for decision, band, _, _ in obs.decisions:
            tally[(decision, band)] = tally.get((decision, band), 0) + 1
        print(f"  {len(obs.decisions)} gate cycles observed:")
        for (decision, band), count in sorted(tally.items(), key=lambda kv: -kv[1]):
            meaning = decision_meaning(decision, band)
            print(f"    {count:>5} x  decision={decision:<10} band={band:<8}  {meaning}")
        _, last_band, candidate, emitted = obs.decisions[-1]
        print(f"  last cycle: candidate {[round(v, 3) for v in candidate]}")
        print(f"              emitted   {[round(v, 3) for v in emitted]}   <- reached the actuator")

    transfers = [e for e in obs.events if e.WhichOneof("body") == "transfer"]
    projections = [e for e in obs.events if e.WhichOneof("body") == "projection"]
    print(
        f"  {len(obs.events)} enforcement events decoded "
        f"({len(projections)} projection, {len(transfers)} transfer)"
    )

    # Transfers are rare and are the story; always show them in full.
    #
    # Projections: show the LAST few, not the first. The upstream controller
    # holds its previous command until a new one is published and propagates,
    # so the events at the head of a scenario window still describe the
    # PREVIOUS scenario's torque — showing those made every scenario look one
    # step behind itself.
    shown = transfers + projections[-limit:]
    for event in shown:
        for line in describe_event(event):
            print(line)

    # Cross-check the two views of the same cycle against each other. In Band B
    # they disagree, and the disagreement matters: ProjectionEvent is emitted
    # in kernel_gate.cpp BEFORE the Output block applies the band fallback, so
    # `emitted` carries the clamped projection rather than the zero that
    # actually went out. enforcement.proto defines that field as "what
    # actually reached the actuator".
    if obs.decisions and projections:
        _, band, _, actual_emitted = obs.decisions[-1]
        logged_emitted = list(projections[-1].emitted)
        if band == "BAND_B" and logged_emitted and actual_emitted:
            if any(
                abs(a - b) > 1e-9 for a, b in zip(actual_emitted, logged_emitted)
            ):
                print(
                    "  !! PROVENANCE MISMATCH: the actuator received "
                    f"{[round(v, 3) for v in actual_emitted]} but the enforcement log records "
                    f"emitted={[round(v, 3) for v in logged_emitted]}.\n"
                    "     ProjectionEvent is written before the Band B fallback is applied, so "
                    "in Band B\n     the logged `emitted` is the clamp, not the output. A "
                    "threshold derived from an\n     episode that entered Band B would be "
                    "derived from values that never reached the robot."
                )

    dropped = sum(e.dropped_since_last for e in obs.events)
    if dropped:
        print(
            f"  !! {dropped} events were dropped for want of ring space. The gate never "
            "blocked to log them — evidence is what degrades under pressure, not enforcement."
        )


def check_ready(node: HarnessFlow) -> bool:
    """Confirm the controller is publishing, and that it is not already in Band B.

    Band B is terminal, so a second run of this script against a controller
    left in Band B by the first would show nothing but zeros and read as a
    broken demo rather than as the (correct) refusal it is.
    """
    node.obs = Observation()
    node.pump(2.5)

    if not node.obs.decisions:
        print(
            "\n  No messages on /harness_controller/decision.\n"
            "  The controller is not active. Check the launch terminal, then:\n"
            "      ros2 control list_controllers\n"
            "  Both harness_controller and upstream_effort_controller should be 'active'."
        )
        return False

    bands = {band for _, band, _, _ in node.obs.decisions}
    if "BAND_B" in bands:
        print(
            "\n  The controller is ALREADY in Band B — a previous run left it there, and\n"
            "  Band B is terminal in this ABI. Everything from here would emit 0.0 and the\n"
            "  walkthrough would be meaningless. Reset it with:\n"
            "      ros2 control set_controller_state harness_controller inactive\n"
            "      ros2 control set_controller_state harness_controller active\n"
            "  (deactivate/activate rebuilds a fresh hk_handle through on_configure)"
        )
        return False

    print(f"  Controller is live and in {'/'.join(sorted(bands))}.")
    return True


