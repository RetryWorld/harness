def run_walkthrough(node: HarnessFlow, auto: bool):
    print(RULE)
    print("harness controller — flow of enforcement")
    print(RULE)
    print(
        "\nTopology: you publish to /upstream_effort_controller/commands; that controller\n"
        "writes into harness_controller's exported reference interfaces; harness_controller\n"
        "runs hk_gate and writes the GATED effort to the hardware. Nothing reaches the\n"
        "effort interface except through the gate — controller_manager's resource manager\n"
        "enforces that exclusivity, so it is not a matter of convention.\n"
    )

    print("Waiting for the controller's publishers…")
    if not check_ready(node):
        return

    for scenario in SCENARIOS:
        print()
        print(RULE)
        print(scenario.title)
        print(RULE)
        print(f"  setup:  {scenario.setup}")
        print(f"  expect: {scenario.expect}")
        if not auto:
            try:
                input("\n  [Enter] to run this scenario, Ctrl-C to stop… ")
            except (EOFError, KeyboardInterrupt):
                print("\nstopped.")
                return
        print()
        obs = node.drive(scenario.torque, scenario.seconds)
        summarise(obs)

    print()
    print(RULE)
    print("Walkthrough complete.")
    print(RULE)
    print(
        "\nOne thing this demo cannot show, deliberately: a NaN command. hk_gate has no\n"
        "finiteness predicate — margin = min(NaN, NaN) is NaN, and NaN < 0.0 is false — so a\n"
        "NaN is ADMITted unclamped, cached as last_admitted, and logged with margin=+inf.\n"
        "See test_gate_loop.cpp::nan_reference_is_admitted_ungated, which pins that gap.\n"
        "Try it with --repl and enter 'nan' if you want to watch it happen.\n"
    )


def run_repl(node: HarnessFlow):
    print(RULE)
    print("harness controller — interactive mode")
    print(RULE)
    print(
        "\nEnter a torque in Nm to command on every joint, and watch what the gate does\n"
        "with it. The declared output region is +/-40 Nm.\n"
        "  try:  5      admitted unchanged\n"
        "        39.9   admitted, almost no margin\n"
        "        60     clamped to 40\n"
        "        nan    admitted ungated — the missing finiteness predicate\n"
        "        inf    clamped, because infinities ARE ordered against the bounds\n"
        "  'q' to quit.\n"
    )
    if not check_ready(node):
        return

    while True:
        try:
            raw = input("torque (Nm) > ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            return
        if raw.lower() in {"q", "quit", "exit"}:
            return
        if not raw:
            continue
        try:
            value = float(raw)  # accepts 'nan' and 'inf' by design
        except ValueError:
            print("  not a number. try 5, 60, nan, inf, or q")
            continue

        obs = node.drive(value, 1.0)
        summarise(obs, limit=2)
        print()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--auto", action="store_true", help="run the walkthrough without waiting for Enter"
    )
    parser.add_argument(
        "--repl", action="store_true", help="type torque values and watch the gate respond"
    )
    parser.add_argument("--joints", type=int, default=3, help="number of gated joints")
    args = parser.parse_args()

    rclpy.init()
    node = HarnessFlow(n_joints=args.joints)
    try:
        if args.repl:
            run_repl(node)
        else:
            run_walkthrough(node, auto=args.auto)
    finally:
        node.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
