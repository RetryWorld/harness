@dataclass
class Observation:
    """Everything seen since the last time the timeline was drained."""

    decisions: list = field(default_factory=list)
    events: list = field(default_factory=list)
    decode_errors: list = field(default_factory=list)


class HarnessFlow(Node):
    def __init__(self, n_joints: int = 3):
        super().__init__("harness_flow")
        self.n_joints = n_joints
        self.obs = Observation()
        self._band_seen = "NOMINAL"

        # Best-effort matches the controller's realtime publishers: a
        # RealtimePublisher drops rather than blocks when it cannot get the
        # lock, so demanding reliability here would misrepresent the transport
        # the controller actually offers.
        qos = QoSProfile(depth=200, reliability=ReliabilityPolicy.BEST_EFFORT)

        self.command_pub = self.create_publisher(
            Float64MultiArray, "/upstream_effort_controller/commands", 10
        )
        self.create_subscription(
            GateStatus, "/harness_controller/gate_status", self._on_decision, qos
        )
        self.create_subscription(
            EnforcementEvents, "/harness_controller/enforcement_events", self._on_events, qos
        )
        # Latched identity. Transient-local so this still arrives even though
        # the controller published it before this script started.
        self.info = None
        self.create_subscription(
            HarnessInfo,
            "/harness_controller/info",
            self._on_info,
            QoSProfile(
                depth=1,
                reliability=ReliabilityPolicy.RELIABLE,
                durability=DurabilityPolicy.TRANSIENT_LOCAL,
            ),
        )

    def _on_info(self, msg: HarnessInfo):
        self.info = msg

    def _on_decision(self, msg: GateStatus):
        decision = DECISION_NAMES.get(msg.decision, f"?{msg.decision}")
        band = BAND_NAMES.get(msg.band, f"?{msg.band}")
        self.obs.decisions.append((decision, band, list(msg.candidate), list(msg.emitted)))

    def _on_events(self, msg: EnforcementEvents):
        # The envelope says what the bytes are. Refusing an unexpected schema
        # beats decoding it as though nothing changed — that is the whole
        # reason the field exists.
        if msg.schema != "harness.v1.EnforcementEvent":
            self.obs.decode_errors.append(f"unexpected schema {msg.schema!r}")
            return
        if msg.encoding != "protobuf-varint-delimited":
            self.obs.decode_errors.append(f"unexpected encoding {msg.encoding!r}")
            return
        try:
            self.obs.events.extend(decode_events(bytes(msg.data)))
        except ValueError as exc:
            self.obs.decode_errors.append(str(exc))

    def publish(self, value: float):
        msg = Float64MultiArray()
        msg.data = [value] * self.n_joints
        self.command_pub.publish(msg)

    def pump(self, seconds: float):
        """Publish nothing, just let callbacks run for a while."""
        deadline = time.time() + seconds
        while time.time() < deadline:
            rclpy.spin_once(self, timeout_sec=0.02)

    def drive(self, value: float, seconds: float) -> Observation:
        """Hold `value` on the command topic for `seconds`, collecting what came back."""
        self.obs = Observation()
        deadline = time.time() + seconds
        while time.time() < deadline:
            self.publish(value)
            rclpy.spin_once(self, timeout_sec=0.02)
        return self.obs


