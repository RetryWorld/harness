#!/usr/bin/env python3
"""Narrate what the harness controller does, when, and under which conditions.

Drives the mock bring-up from the outside — publishing exactly where a policy
would publish, reading exactly what a customer's ingest would read — and
prints a decoded, annotated timeline of every decision the gate makes.

    ros2 launch harness_controller harness_mock.launch.py     # terminal 1
    ros2 run harness_controller harness_flow.py               # terminal 2

Modes:
    (default)   guided walkthrough, one scenario at a time, Enter to advance
    --auto      run the whole walkthrough unattended (for CI / recording)
    --repl      type torque values and watch the gate respond

What it subscribes to. Three topics, deliberately different in kind:

  /harness_controller/info                harness_msgs/HarnessInfo
      Latched (transient-local), published once per activation: profile
      identity, the ordered joint names, the joint-order hash and the declared
      bounds. Every positional array below is indexed by that ordering, and
      reading them without it is a mistake no wire format can prevent.

  /harness_controller/gate_status         harness_msgs/GateStatus
      The OPERATIONAL view, one message per control cycle: decision, band,
      candidate and emitted. Says WHAT happened, in a form an integrator can
      wire into their own logic without decoding protobuf. `emitted` here is
      authoritative for what reached the actuator.

  /harness_controller/enforcement_events  harness_msgs/EnforcementEvents
      A TAP on the kernel's event ring — NOT the system of record, which is
      the MCAP episode written in-process. A self-describing envelope
      (schema + encoding) around varint-delimited harness.v1.EnforcementEvent
      protobufs. Says WHY: which predicate failed, the signed margin, sequence
      numbers, and how many events were dropped for want of ring space.

Enforcement itself appears on none of them. The gate runs on ros2_control's
command/state interfaces, in-process and synchronous with the update loop;
these topics describe it and never carry it. And the controller republishes
the event bytes without parsing them, so protobuf decoding never touches the
control loop — it happens out here, which is exactly the split intended.

Operational health also goes to /diagnostics as a DiagnosticArray, where a
customer's existing rqt_robot_monitor or aggregator picks it up for free.
"""

from __future__ import annotations

import argparse
import math
import os
import sys
import time
from dataclasses import dataclass, field

import rclpy
from harness_msgs.msg import EnforcementEvents, GateStatus, HarnessInfo
from rclpy.node import Node
from rclpy.qos import DurabilityPolicy, QoSProfile, ReliabilityPolicy
from std_msgs.msg import Float64MultiArray


def _load_generated_protobuf():
    """Import the committed harness.v1 Python bindings.

    Generated code is committed (schemas/README.md) and generated by the same
    protoc the C++ side uses, so the decoder here and the encoder in the
    kernel cannot drift apart without CI's codegen-drift gate noticing.
    """
    candidates = []
    env = os.environ.get("HARNESS_SCHEMAS_PY")
    if env:
        candidates.append(env)

    # Walk up from both the script and the working directory looking for
    # schemas/gen/python. A fixed number of ".." steps would only be right in
    # the source tree: installed (install/harness_controller/lib/
    # harness_controller/) the script sits at a completely different depth,
    # and with --symlink-install it sits at yet another.
    def _walk_up(start: str):
        current = os.path.abspath(start)
        while True:
            candidate = os.path.join(current, "schemas", "gen", "python")
            if os.path.isdir(candidate):
                return candidate
            parent = os.path.dirname(current)
            if parent == current:
                return None
            current = parent

    for start in (os.path.dirname(os.path.abspath(__file__)), os.getcwd()):
        found = _walk_up(start)
        if found:
            candidates.append(found)

    for path in candidates:
        if os.path.isdir(path) and path not in sys.path:
            sys.path.insert(0, path)
    try:
        from harness.v1 import enforcement_pb2  # noqa: WPS433 (deliberate late import)

        return enforcement_pb2
    except ImportError as exc:
        sys.exit(
            f"could not import harness.v1.enforcement_pb2 ({exc}).\n"
            f"Tried: {candidates}\n"
            "Set HARNESS_SCHEMAS_PY to <repo>/schemas/gen/python, and make sure "
            "'buf generate' has been run (scripts/regen_schemas_and_build_edge.sh)."
        )


pb = _load_generated_protobuf()

