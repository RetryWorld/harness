# Mirrors hk_decision / hk_band in edge/include/harness/harness_kernel.h.
# NOT the same numbering as harness.v1.Band on the wire, which carries an
# extra UNSPECIFIED=0 — see wire_band() in kernel_gate.cpp. Keeping both
# tables here rather than casting between them is the whole point.
DECISION_NAMES = {0: "ADMIT", 1: "CLAMP", 2: "HOLD_LAST", 3: "REJECT"}
BAND_NAMES = {0: "NOMINAL", 1: "BAND_A", 2: "BAND_B"}

_NOMINAL_MEANING = {
    "ADMIT": "candidate was inside every bound; it reached the actuator unchanged",
    "CLAMP": "candidate violated a bound and was replaced by the bound itself",
}

# In Band B the decision code means something different, and reading it with
# the nominal table is actively misleading: kernel_gate.cpp reports HK_CLAMP
# for an on_reject=ZERO fallback, so a a perfectly legal command shows up as
# "CLAMP" while what actually goes out is zero. Nothing was clamped to a
# bound — authority simply is not with the model any more.
_BAND_B_MEANING = {
    "CLAMP": "Band B fallback: emitting ZERO (profile on_reject=ZERO) — NOT a clamp to a bound",
    "REJECT": "Band B fallback: refusing to emit (on_reject=REJECT)",
    "HOLD_LAST": "Band B fallback: re-emitting the last admitted command (on_reject=HOLD_LAST)",
}


def decision_meaning(decision: str, band: str) -> str:
    if band == "BAND_B":
        return _BAND_B_MEANING.get(decision, "Band B fallback output")
    return _NOMINAL_MEANING.get(decision, "")


def read_varint(buf: bytes, pos: int) -> tuple[int, int]:
    """Decode one base-128 varint. Returns (value, next_pos)."""
    result = 0
    shift = 0
    while pos < len(buf):
        byte = buf[pos]
        pos += 1
        result |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return result, pos
        shift += 7
        if shift > 63:
            raise ValueError("varint longer than 64 bits — buffer is not a valid event frame")
    raise ValueError("truncated varint at end of buffer")


def decode_events(raw: bytes) -> list:
    """Split one drained ring buffer into EnforcementEvents.

    Framing is written by try_write_event() in edge/src/kernel/event_sink.hpp:
    a varint byte-length followed by that many bytes of serialised
    harness.v1.EnforcementEvent, repeated until the buffer is consumed.
    """
    events = []
    pos = 0
    while pos < len(raw):
        length, pos = read_varint(raw, pos)
        chunk = raw[pos : pos + length]
        if len(chunk) < length:
            raise ValueError("truncated event body — drained fewer bytes than the prefix claims")
        pos += length
        event = pb.EnforcementEvent()
        event.ParseFromString(bytes(chunk))
        events.append(event)
    return events


def describe_projection(event) -> list[str]:
    """Render a ProjectionEvent the way a reviewer needs to read it."""
    proj = event.projection
    verdict = pb.Verdict.Name(proj.verdict)
    lines = [f"      verdict     {verdict}"]

    if proj.failed:
        failed = ", ".join(pb.Predicate.Name(p) for p in proj.failed)
        lines.append(f"      failed      {failed}")

    # margin is the signed distance to the nearest bound across all joints:
    # positive is headroom, negative is how far past the bound the worst joint
    # went. +inf means no joint was ordered against its bounds at all, which
    # in practice means a NaN candidate (see the note printed on that case).
    if math.isinf(proj.margin):
        lines.append(f"      margin      {proj.margin}   <-- no joint compared against its bound")
    else:
        sense = "headroom" if proj.margin >= 0 else "past the bound"
        lines.append(f"      margin      {proj.margin:+.4f} Nm ({sense})")

    lines.append(f"      candidate   {[round(v, 4) for v in proj.candidate]}")
    lines.append(f"      emitted     {[round(v, 4) for v in proj.emitted]}")
    return lines


def describe_transfer(event) -> list[str]:
    tr = event.transfer
    lines = [
        f"      {pb.Band.Name(tr.from_band)} -> {pb.Band.Name(tr.to_band)}",
        f"      trigger     {tr.trigger}",
    ]
    if tr.to_node:
        lines.append(f"      to_node     {tr.to_node}")
    if tr.recovery_ref:
        lines.append(f"      recovery    {tr.recovery_ref}")
    if tr.preempted_band_a:
        lines.append("      preempted an in-flight Band A recovery")
    return lines


def describe_event(event) -> list[str]:
    mechanism = pb.Mechanism.Name(event.mechanism)
    head = f"  [seq {event.seq:>5}] {mechanism}"
    if event.dropped_since_last:
        head += f"   (!! {event.dropped_since_last} event(s) dropped since the last one)"
    lines = [head]

    body = event.WhichOneof("body")
    if body == "projection":
        lines += describe_projection(event)
    elif body == "transfer":
        lines += describe_transfer(event)
    elif body == "isolation":
        iso = event.isolation
        lines.append(
            f"      inference   {iso.inference_ms:.3f} ms against a "
            f"{iso.wcet_budget_ms:.3f} ms budget"
            + ("   OVERRUN" if iso.compute_overrun else "")
        )
    elif body == "critic":
        cr = event.critic
        lines.append(f"      critic      {cr.critic_id} / {cr.evidence_class}")
        lines.append(f"      confidence  {cr.confidence:.3f}")
    elif body == "reentry":
        re_ = event.reentry
        verdict = "PASS" if re_.predicate_result else f"DENIED ({re_.denied_reason})"
        lines.append(f"      reentry     {verdict}, retry {re_.retry_index}")
    return lines


